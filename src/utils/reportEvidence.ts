import { PostMedia } from '../types/domain';

const AI_GENERATION_MARKERS =
  /\b(?:stable diffusion|midjourney|dall[\s-]?e|firefly|imagen|sora|runway(?:ml)?|pika labs|generative fill|generated by ai|ai[- ]generated|text[- ]to[- ](?:image|video))\b/i;

const persistedMediaTypes = new Map<string, PostMedia['type']>();

export function hasExplicitAIGenerationMarker(bytes: Uint8Array): boolean {
  const metadataText = new TextDecoder().decode(bytes);
  return AI_GENERATION_MARKERS.test(metadataText);
}

export function registerReportMediaType(url: string, mimeType: string): void {
  if (mimeType.startsWith('video/')) persistedMediaTypes.set(url, 'video');
  else if (mimeType.startsWith('image/')) persistedMediaTypes.set(url, 'image');
}

export function getReportMediaType(url: string): PostMedia['type'] {
  const persistedType = persistedMediaTypes.get(url);
  if (persistedType) return persistedType;
  if (/^data:video\//i.test(url) || /\.(?:mp4|webm|mov)(?:[?#]|$)/i.test(url)) {
    return 'video';
  }
  return 'image';
}

export function hasRequiredReportEvidence(mediaUrls: string[]): boolean {
  const providedMedia = mediaUrls.filter(Boolean);
  return providedMedia.some((url) => getReportMediaType(url) === 'image')
    && providedMedia.some((url) => getReportMediaType(url) === 'video');
}
